local torch = require("torch")

test("tensor-tensor arithmetic", function()
  local a = torch.tensor({ 1, 2, 3 })
  local b = torch.tensor({ 10, 20, 30 })
  assert_tensor(a:add(b), { 11, 22, 33 })
  assert_tensor(a:sub(b), { -9, -18, -27 })
  assert_tensor(a:mul(b), { 10, 40, 90 })
  assert_tensor(b:div(a), { 10, 10, 10 })
  assert_tensor(a:pow(torch.tensor({ 2, 2, 2 })), { 1, 4, 9 })
end)

test("scalar arithmetic", function()
  local a = torch.tensor({ 1, 2, 3 })
  assert_tensor(a:add(4), { 5, 6, 7 })
  assert_tensor(a:sub(1), { 0, 1, 2 })
  assert_tensor(a:mul(3), { 3, 6, 9 })
  assert_tensor(a:div(2), { 0.5, 1, 1.5 })
  assert_tensor(a:pow(2), { 1, 4, 9 })
end)

test("operators", function()
  local a = torch.tensor({ 1, 2, 3 })
  local b = torch.tensor({ 4, 5, 6 })
  assert_tensor(a + b, { 5, 7, 9 })
  assert_tensor(b - a, { 3, 3, 3 })
  assert_tensor(a * 2, { 2, 4, 6 })
  assert_tensor(2 * a, { 2, 4, 6 })
  assert_tensor(2 - a, { 1, 0, -1 })
  assert_tensor(1 / a, { 1, 0.5, 1 / 3 })
  assert_tensor(a ^ 2, { 1, 4, 9 })
  assert_tensor(2 ^ a, { 2, 4, 8 })
  assert_tensor(-a, { -1, -2, -3 })
end)

test("broadcasting", function()
  local column = torch.ones(2, 1)
  local row = torch.ones(1, 3)
  local sum = column:add(row)
  assert_shape(sum, { 2, 3 })
  assert_tensor(sum, { { 2, 2, 2 }, { 2, 2, 2 } })

  local scaled = torch.tensor({ { 1, 2, 3 }, { 4, 5, 6 } }):mul(torch.tensor({ 10, 20, 30 }))
  assert_tensor(scaled, { { 10, 40, 90 }, { 40, 100, 180 } })
end)

test("in-place ops return self", function()
  local t = torch.tensor({ 1, 2, 3 })
  assert_true(t:add_(1) == t)
  assert_tensor(t, { 2, 3, 4 })
  t:sub_(1):mul_(2)
  assert_tensor(t, { 2, 4, 6 })
  t:div_(2):pow_(2)
  assert_tensor(t, { 1, 4, 9 })
  t:fill_(0)
  assert_tensor(t, { 0, 0, 0 })
end)

test("unary math", function()
  local t = torch.tensor({ -2, -1, 0, 1, 2 })
  assert_tensor(t:abs(), { 2, 1, 0, 1, 2 })
  assert_tensor(t:neg(), { 2, 1, 0, -1, -2 })
  assert_tensor(t:sign(), { -1, -1, 0, 1, 1 })
  assert_tensor(t:square(), { 4, 1, 0, 1, 4 })

  local positive = torch.tensor({ 1, 4, 9 })
  assert_tensor(positive:sqrt(), { 1, 2, 3 })
  assert_near(positive:rsqrt():totable(), { 1, 0.5, 1 / 3 })

  assert_near(torch.tensor(1):exp():item(), math.exp(1), 1e-6)
  assert_near(torch.tensor(math.exp(1)):log():item(), 1, 1e-6)
  assert_near(torch.tensor(1):log1p():item(), math.log(2), 1e-6)

  assert_near(torch.tensor(0.5):sin():item(), math.sin(0.5), 1e-6)
  assert_near(torch.tensor(0.5):cos():item(), math.cos(0.5), 1e-6)
  assert_near(torch.tensor(0.5):tan():item(), math.tan(0.5), 1e-6)
  assert_near(torch.tensor(0.5):asin():item(), math.asin(0.5), 1e-6)
  assert_near(torch.tensor(0.5):acos():item(), math.acos(0.5), 1e-6)
  assert_near(torch.tensor(0.5):atan():item(), math.atan(0.5), 1e-6)
  assert_near(torch.tensor(0.5):tanh():item(), math.tanh(0.5), 1e-6)
  assert_near(torch.tensor(0.5):sigmoid():item(), 1 / (1 + math.exp(-0.5)), 1e-6)

  assert_tensor(torch.tensor({ -1, 2 }):relu(), { 0, 2 })
  assert_tensor(torch.tensor({ 1.4, -1.4 }):floor(), { 1, -2 })
  assert_tensor(torch.tensor({ 1.4, -1.4 }):ceil(), { 2, -1 })
  assert_tensor(torch.tensor({ 1.6, -1.6 }):round(), { 2, -2 })
  assert_tensor(torch.tensor({ 1.6, -1.6 }):trunc(), { 1, -1 })
  assert_near(torch.tensor({ 2, 4 }):reciprocal():totable(), { 0.5, 0.25 })
end)

test("in-place unary", function()
  local t = torch.tensor({ -1, 0, 2 })
  t:relu_()
  assert_tensor(t, { 0, 0, 2 })
  t:add_(1)
  t:log_()
  assert_near(t:totable(), { 0, 0, math.log(3) }, 1e-5)
end)

test("clamp", function()
  local t = torch.tensor({ -5, -1, 0, 1, 5 })
  assert_tensor(t:clamp(-1, 1), { -1, -1, 0, 1, 1 })
  t:clamp_(-2, 2)
  assert_tensor(t, { -2, -1, 0, 1, 2 })
end)

test("maximum and minimum", function()
  local a = torch.tensor({ 1, 5, 3 })
  local b = torch.tensor({ 4, 2, 3 })
  assert_tensor(a:maximum(b), { 4, 5, 3 })
  assert_tensor(a:minimum(b), { 1, 2, 3 })
  assert_error(function()
    a:maximum(1)
  end, "Tensor or a number")
end)

test("comparisons", function()
  local a = torch.tensor({ 1, 2, 3 })
  local b = torch.tensor({ 3, 2, 1 })
  assert_tensor(a:eq(b), { false, true, false })
  assert_tensor(a:ne(b), { true, false, true })
  assert_tensor(a:lt(b), { true, false, false })
  assert_tensor(a:le(b), { true, true, false })
  assert_tensor(a:gt(b), { false, false, true })
  assert_tensor(a:ge(b), { false, true, true })
  assert_tensor(a:gt(2), { false, false, true })
  assert_dtype(a:gt(2), "bool")
end)

test("logical ops", function()
  local a = torch.tensor({ true, true, false, false })
  local b = torch.tensor({ true, false, true, false })
  assert_tensor(a:logical_and(b), { true, false, false, false })
  assert_tensor(a:logical_or(b), { true, true, true, false })
  assert_tensor(a:logical_not(), { false, false, true, true })
end)

test("remainder", function()
  local a = torch.tensor({ 5, 7, 9 })
  assert_tensor(a:remainder(3), { 2, 1, 0 })
  assert_tensor(a:remainder(torch.tensor({ 2, 4, 5 })), { 1, 3, 4 })
end)

test("matrix multiplication", function()
  local a = torch.tensor({ { 1, 2, 3 }, { 4, 5, 6 } })
  local b = torch.tensor({ { 7, 8 }, { 9, 10 }, { 11, 12 } })
  assert_tensor(a:matmul(b), { { 58, 64 }, { 139, 154 } })
  assert_tensor(a:mm(b), { { 58, 64 }, { 139, 154 } })

  local batched_a = torch.ones(2, 2, 3)
  local batched_b = torch.ones(2, 3, 2)
  local batched = batched_a:bmm(batched_b)
  assert_shape(batched, { 2, 2, 2 })
  assert_tensor(batched, { { { 3, 3 }, { 3, 3 } }, { { 3, 3 }, { 3, 3 } } })
end)

test("dot", function()
  local a = torch.tensor({ 1, 2, 3 })
  local b = torch.tensor({ 4, 5, 6 })
  assert_near(a:dot(b):item(), 32)
end)

test("where", function()
  local condition = torch.tensor({ true, false, true })
  local a = torch.tensor({ 1, 2, 3 })
  local b = torch.tensor({ 4, 5, 6 })
  assert_tensor(torch.where(condition, a, b), { 1, 5, 3 })
end)

test("masked_fill", function()
  local t = torch.tensor({ { 1, 2 }, { 3, 4 } })
  local mask = t:gt(2)
  assert_tensor(t:masked_fill(mask, -1), { { 1, 2 }, { -1, -1 } })
end)

test("Torch7 cmul/cdiv aliases", function()
  local a = torch.tensor({ 2, 4, 6 })
  local b = torch.tensor({ 3, 2, 1 })
  assert_tensor(a:cmul(b), { 6, 8, 6 })
  assert_tensor(a:cdiv(b), { 2 / 3, 2, 6 })
  local c = torch.tensor({ 1, 2 })
  c:cmul_(torch.tensor({ 5, 6 }))
  assert_tensor(c, { 5, 12 })
end)

test("module-level operator aliases", function()
  local a = torch.tensor({ 1, 2, 3 })
  assert_tensor(torch.add(a, 1), { 2, 3, 4 })
  assert_tensor(torch.sub(a, 1), { 0, 1, 2 })
  assert_tensor(torch.mul(a, 2), { 2, 4, 6 })
  assert_tensor(torch.div(a, 2), { 0.5, 1, 1.5 })
  assert_tensor(torch.pow(a, 2), { 1, 4, 9 })
  assert_tensor(torch.relu(torch.tensor({ -1, 0, 2 })), { 0, 0, 2 })
  assert_near(torch.sum(a):item(), 6)
  assert_near(torch.mean(a):item(), 2)
  assert_near(torch.dot(a, a):item(), 14)
  assert_tensor(torch.reshape(a, 3, 1), { { 1 }, { 2 }, { 3 } })
  assert_tensor(torch.transpose(torch.zeros(2, 3), 1, 2), { { 0, 0 }, { 0, 0 }, { 0, 0 } })
end)

test("trapezoid integrates with uniform spacing", function()
  local y = torch.tensor({ 1, 2, 3 }, { dtype = torch.float64 })
  assert_near(torch.trapezoid(y):item(), 4, 1e-12)
  assert_near(torch.trapezoid(y, nil, { dx = 2 }):item(), 8, 1e-12)
  assert_near(y:trapezoid(nil, { dx = 0.5 }):item(), 2, 1e-12)

  -- The default dimension is the last one.
  local matrix = torch.tensor({ { 1, 2, 3 }, { 4, 5, 6 } },
    { dtype = torch.float64 })
  assert_tensor(matrix:trapezoid(), { 4, 10 })
  assert_tensor(torch.trapezoid(matrix, { dx = 2 }), { 8, 20 })
  assert_tensor(matrix:trapezoid(nil, { dim = 1 }), { 2.5, 3.5, 4.5 })
end)

test("trapezoid supports non-uniform sample positions", function()
  local y = torch.tensor({ 1, 2, 3 }, { dtype = torch.float64 })
  local x = torch.tensor({ 0, 1, 3 }, { dtype = torch.float64 })
  assert_near(torch.trapezoid(y, x):item(), 6.5, 1e-12)
  -- Integral inputs are promoted to the sample dtype.
  assert_near(torch.trapezoid(y,
    torch.tensor({ 0, 1, 3 }, { dtype = torch.int64 })):item(), 6.5, 1e-12)

  local matrix = torch.tensor({ { 1, 2, 3 }, { 4, 5, 6 } },
    { dtype = torch.float64 })
  -- A 1-D x is reused along the chosen dimension.
  local x2 = torch.tensor({ 0, 1 }, { dtype = torch.float64 })
  assert_tensor(matrix:trapezoid(x2, { dim = 1 }), { 2.5, 3.5, 4.5 })

  -- A same-shape x allows per-slice spacing.
  local positions = torch.tensor({ { 0, 1, 3 }, { 0, 2, 3 } },
    { dtype = torch.float64 })
  assert_tensor(matrix:trapezoid(positions, { dim = 2 }), { 6.5, 14.5 })
end)

test("trapezoid handles short dimensions", function()
  assert_near(torch.trapezoid(
    torch.tensor({ 3 }, { dtype = torch.float64 })):item(), 0, 1e-12)
  local empty = torch.trapezoid(torch.tensor({}, { dtype = torch.float64 }))
  assert_shape(empty, {})
  assert_near(empty:item(), 0, 1e-12)

  local rows = torch.zeros(2, 0, { dtype = torch.float64 }):trapezoid()
  assert_shape(rows, { 2 })
  assert_tensor(rows, { 0, 0 })
end)

test("trapezoid validates arguments", function()
  local y = torch.tensor({ 1, 2, 3 }, { dtype = torch.float64 })
  assert_error(function()
    y:trapezoid(nil, { dim = 0 })
  end, "non-zero integer")
  assert_error(function()
    y:trapezoid(nil, { dim = 2 })
  end, "out of range")
  assert_error(function()
    y:trapezoid(torch.tensor({ 0, 1 }, { dtype = torch.float64 }), {})
  end, "one value per sample")
  assert_error(function()
    torch.zeros(2, 3, { dtype = torch.float64 }):trapezoid(
      torch.ones(2, 2, { dtype = torch.float64 }))
  end, "same shape")
  assert_error(function()
    y:trapezoid(torch.tensor({ 0, 1, 2 }, { dtype = torch.float32 }))
  end, "dtype must match")
  assert_error(function()
    y:trapezoid(torch.tensor({ 0, 1, 2 }, { dtype = torch.float64 }),
      { dx = 1 })
  end, "either x or dx")
  assert_error(function()
    torch.trapezoid(y, 2)
  end, "x must be a Tensor")
  assert_error(function()
    torch.trapezoid(torch.tensor({ 1, 2, 3 }, { dtype = torch.int64 }))
  end, "floating-point")
  assert_error(function()
    torch.trapezoid(torch.tensor({ true, false }))
  end, "floating-point")
  assert_error(function()
    torch.trapezoid(torch.tensor(3.0))
  end, "at least one dimension")
end)
