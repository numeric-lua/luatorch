-- Special functions: bessel_j0, polygamma, mvlgamma, igamma, igammac.

local torch = require("torch")

test("bessel_j0 evaluates the order-zero Bessel function", function()
  local values = torch.tensor({0, 1, 2}, {dtype = torch.float64})
  local result = values:bessel_j0()
  assert_eq(result:get(1), 1)
  assert_near(result:get(2), 0.7651976865579666, 1e-12)
  assert_near(result:get(3), 0.22389077914123567, 1e-12)
  assert_near(torch.bessel_j0(values):get(2), result:get(2), 1e-12)
  assert_near(torch.special.bessel_j0(values):get(2), result:get(2), 1e-12)
  local in_place = torch.tensor({0}, {dtype = torch.float64})
  assert_eq(in_place:bessel_j0_():get(1), 1)
end)

test("polygamma matches digamma and trigamma values", function()
  local values = torch.tensor({1, 2}, {dtype = torch.float64})
  assert_near(values:polygamma(0):get(1), -0.5772156649015329, 1e-12)
  assert_near(values:polygamma(1):get(1), math.pi * math.pi / 6, 1e-8)
  assert_near(torch.polygamma(1, values):get(2), 0.6449340668482264, 1e-8)
  local in_place = torch.tensor({1}, {dtype = torch.float64})
  assert_near(in_place:polygamma_(1):get(1), math.pi * math.pi / 6, 1e-8)
end)

test("mvlgamma with order one equals lgamma", function()
  local values = torch.tensor({2, 3}, {dtype = torch.float64})
  local result = values:mvlgamma(1)
  assert_true(result:allclose(values:lgamma(), 1e-12, 1e-12))
  assert_near(torch.mvlgamma(values, 1):get(1), 0, 1e-12)
  local in_place = torch.tensor({2}, {dtype = torch.float64})
  assert_near(in_place:mvlgamma_(1):get(1), 0, 1e-12)
end)

test("igamma and igammac are complementary", function()
  local a = torch.tensor({1, 2}, {dtype = torch.float64})
  local x = torch.tensor({1, 2}, {dtype = torch.float64})
  local lower = a:igamma(x)
  local upper = a:igammac(x)
  assert_near(lower:get(1), 0.6321205588285577, 1e-12)
  assert_near(upper:get(1), 0.36787944117144233, 1e-12)
  assert_true(lower:add(upper):allclose(torch.ones(2,
    {dtype = torch.float64}), 1e-12, 1e-12))
  assert_near(torch.igamma(a, x):get(1), lower:get(1), 1e-12)
  assert_near(torch.igammac(a, x):get(1), upper:get(1), 1e-12)
  assert_near(torch.special.igamma(a, x):get(1), lower:get(1), 1e-12)
  assert_near(torch.special.igammac(a, x):get(1), upper:get(1), 1e-12)
end)

test("incomplete gamma functions support in-place calls", function()
  local lower = torch.tensor({1}, {dtype = torch.float64})
  local result = lower:igamma_(torch.tensor({1}, {dtype = torch.float64}))
  assert_true(result == lower)
  assert_near(lower:get(1), 0.6321205588285577, 1e-12)

  local upper = torch.tensor({1}, {dtype = torch.float64})
  assert_true(upper:igammac_(torch.tensor({1},
    {dtype = torch.float64})) == upper)
  assert_near(upper:get(1), 0.36787944117144233, 1e-12)
end)

test("special function orders and operands are validated", function()
  local values = torch.tensor({1}, {dtype = torch.float64})
  assert_error(function() values:polygamma(-1) end, "non-negative")
  assert_error(function() values:polygamma(1.5) end, "integer")
  assert_error(function() values:mvlgamma(0) end, "positive")
  assert_error(function() values:mvlgamma(1.5) end, "integer")
  assert_error(function() values:igamma(1) end, "expects a tensor")
  assert_error(function() values:igammac(1) end, "expects a tensor")
  assert_error(function() torch.polygamma(1, 1) end, "second argument")
  assert_error(function() torch.mvlgamma(1, 1) end, "first argument")
end)
